def expand_queries(
    question: str, enabled: bool = True, max_variants: int = 3
) -> list[str]:
    """返回用于多路召回的查询变体，第 0 条恒为原句；关掉或空输入时只返回原句。"""
    q = (question or "").strip()
    if not q:
        return []
    if not enabled:
        return [q]

    canonical: list[str] = []
    seen: set[str] = set()
    for trigger, alts in SYNONYM_MAP.items():
        if trigger in q:
            for a in alts:
                if a not in seen and a not in q:
                    seen.add(a)
                    canonical.append(a)

    variants = [q]
    if canonical:
        canon_str = " ".join(canonical[:6])   # 控制补词规模，避免稀释语义
        variants.append(canon_str)            # 纯规范词：强化关键词命中
        variants.append(f"{q} {canon_str}")   # 原句补规范词：兼顾语义与关键词

    out: list[str] = []
    for v in variants:
        if v and v not in out:
            out.append(v)
    return out[: max(1, max_variants)]
